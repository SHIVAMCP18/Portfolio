#!/usr/bin/env python3
"""Bundle phase dumps into viewer/samples/samples.js so the viewer can show a demo
when opened straight from disk (file:// pages cannot fetch() local JSON)."""
import json
import sys
from pathlib import Path

out = Path(sys.argv[1])
parts = []
for p in sys.argv[2:]:
    data = json.loads(Path(p).read_text())
    parts.append(f"  {json.dumps(Path(p).name)}: {json.dumps(data, separators=(',', ':'))}")
out.write_text("// Generated by `make examples` (tools/make_samples.py). Demo dumps for the viewer.\n"
               "window.QS_SAMPLES = {\n" + ",\n".join(parts) + "\n};\n")
